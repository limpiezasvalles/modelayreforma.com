#!/usr/bin/env node
/**
 * build-videos.mjs — static generator for the video section.
 *
 * Reads data/videos.json and writes plain HTML (content + JSON-LD) between
 * `<!-- videos:NAME:start -->` / `<!-- videos:NAME:end -->` markers in the site
 * pages, generates videos.html and updates sitemap.xml. No dependencies.
 *
 *   node scripts/build-videos.mjs             write files
 *   node scripts/build-videos.mjs --check     exit 1 if files are out of date
 *   node scripts/build-videos.mjs --preview D copy the site to D and build it with
 *                                             FAKE ids (for local testing only)
 *
 * While "published" is false, or no video has both youtubeId and uploadDate,
 * every block stays empty, videos.html is not written and the sitemap is untouched.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GENERATED = '<!-- generated by scripts/build-videos.mjs -->';
const ID_RE = /^[A-Za-z0-9_-]{11}$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

/* ---------- helpers ---------- */
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const jsonLd = (obj) => JSON.stringify(obj, null, 2).replace(/</g, '\\u003c');

function isoDuration(sec) {
  const m = Math.floor(sec / 60), s = sec % 60;
  return 'PT' + (m ? `${m}M` : '') + (s || !m ? `${s}S` : '');
}
const gcd = (a, b) => (b ? gcd(b, a % b) : a);
/** CSS class holding the exact display aspect ratio of a video, e.g. video-facade--ar-9-16 */
function ratioClass(v) {
  const { width, height } = v.display;
  const g = gcd(width, height);
  return `video-facade--ar-${width / g}-${height / g}`;
}
function indent(text, pad) {
  return text.split('\n').map((l) => (l ? pad + l : l)).join('\n');
}

/** Replace what sits between the markers called `name`; keep the markers. */
function patch(text, name, content) {
  const re = new RegExp(`([ \\t]*)<!-- videos:${name}:start -->[\\s\\S]*?<!-- videos:${name}:end -->`);
  if (!re.test(text)) return text;
  return text.replace(re, (_m, pad) => {
    const body = content ? `\n${indent(content, pad)}\n${pad}` : `\n${pad}`;
    return `${pad}<!-- videos:${name}:start -->${body}<!-- videos:${name}:end -->`;
  });
}

/* ---------- data ---------- */
function loadVideos(data, preview) {
  const list = data.videos.map((v, i) => ({ ...v }));
  if (preview) {
    list.forEach((v, i) => { v.youtubeId = `PREVIEW${String(i).padStart(4, '0')}`; v.uploadDate = '2026-01-01'; });
  }
  const live = data.published || preview
    ? list.filter((v) => ID_RE.test(v.youtubeId || '') && DATE_RE.test(v.uploadDate || ''))
    : [];
  const skipped = (data.published || preview) ? list.filter((v) => !live.includes(v)) : [];
  return { live, skipped };
}

/* ---------- renderers ---------- */
function videoLd(v, site) {
  return {
    '@context': 'https://schema.org',
    '@type': 'VideoObject',
    name: v.title,
    description: v.description,
    thumbnailUrl: `${site}/${v.thumbnail}`,
    uploadDate: v.uploadDate,
    duration: isoDuration(v.durationSeconds),
    embedUrl: `https://www.youtube-nocookie.com/embed/${v.youtubeId}`,
    publisher: { '@type': 'Organization', name: 'Modela y Reforma', url: site },
  };
}
const ldScript = (obj) => `<script type="application/ld+json">\n${indent(jsonLd(obj), '  ')}\n</script>`;

function card(v, { level = 3, showText = false } = {}) {
  const h = `h${level}`;
  return `<article class="video-card">
  <div class="video-facade ${ratioClass(v)}" data-video-id="${esc(v.youtubeId)}" data-video-title="${esc(v.title)}">
    <img class="video-facade__thumb" src="${esc(v.thumbnail)}" alt="${esc(v.thumbnailAlt)}" width="${v.thumbnailWidth}" height="${v.thumbnailHeight}" loading="lazy" decoding="async">
    <button class="video-facade__play" type="button" aria-label="Reproducir vídeo: ${esc(v.title)}">
      <span class="video-facade__icon" aria-hidden="true">
        <svg xmlns="http://www.w3.org/2000/svg" width="28" height="28" viewBox="0 0 24 24" fill="currentColor"><polygon points="8 5 20 12 8 19 8 5"/></svg>
      </span>
    </button>
  </div>
  <div class="video-card__body">
    <${h} class="video-card__title">${esc(v.title)}</${h}>${showText ? `
    <p class="video-card__text">${esc(v.description)}</p>` : ''}
    <p class="video-card__links">
      <a href="https://www.youtube.com/watch?v=${esc(v.youtubeId)}" target="_blank" rel="noopener noreferrer">Ver en YouTube<span class="video-card__ext"> (se abre en otra pestaña)</span></a>
    </p>
  </div>
</article>`;
}

const CHEVRON = (d) => `<svg xmlns="http://www.w3.org/2000/svg" width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><polyline points="${d}"/></svg>`;

/** One horizontal carousel (native scroll-snap; prev/next buttons are enhanced by js/main.js)
 *  followed by the single YouTube notice of the block. */
function carousel(videos, label, opts) {
  return `<div class="video-carousel">
  <button class="video-carousel__btn video-carousel__btn--prev" type="button" aria-label="Vídeos anteriores" disabled>
    ${CHEVRON('15 18 9 12 15 6')}
  </button>
  <div class="video-carousel__viewport" role="region" aria-roledescription="carrusel" aria-label="${esc(label)}" tabindex="0">
    <div class="video-carousel__track">
${indent(videos.map((v) => card(v, opts)).join('\n'), '      ')}
    </div>
  </div>
  <button class="video-carousel__btn video-carousel__btn--next" type="button" aria-label="Vídeos siguientes">
    ${CHEVRON('9 18 15 12 9 6')}
  </button>
</div>
<p class="video-note">Al pulsar play se carga contenido de YouTube (Google). Más información en la <a href="politica-cookies.html">política de cookies</a>.</p>`;
}

function homeSection(live, data) {
  const featured = live.filter((v) => v.featured);
  if (!featured.length) return '';
  return `<section class="section section--light" id="videos" aria-labelledby="videos-title">
  <div class="container">
    <div class="section__header" data-animate="fade-up">
      <span class="section__label">Vídeos</span>
      <h2 class="section__title" id="videos-title">Nuestras reformas en vídeo</h2>
      <p class="section__subtitle">
        Obras reales en Sabadell, del derribo al resultado final.
      </p>
    </div>
${indent(carousel(featured, 'Vídeos destacados de reformas en Sabadell', { showText: false }), '    ')}
    <p class="video-more"><a class="btn btn--primary" href="videos.html">Ver todos los vídeos</a></p>
  </div>
</section>`;
}

function serviceSection(live, data, serviceKey) {
  const mine = live.filter((v) => v.service === serviceKey);
  if (!mine.length) return '';
  const svc = data.services[serviceKey];
  return `<section class="section section--white" id="videos" aria-labelledby="videos-title">
  <div class="container">
    <div class="section__header" data-animate="fade-up">
      <span class="section__label">Vídeos</span>
      <h2 class="section__title" id="videos-title">${esc(svc.sectionTitle)}</h2>
      <p class="section__subtitle">${esc(svc.sectionIntro)}</p>
    </div>
${indent(carousel(mine, `Vídeos del servicio: ${svc.name}`, { showText: false }), '    ')}
    <p class="video-more"><a class="btn btn--primary" href="videos.html">Ver todos los vídeos</a></p>
  </div>
</section>`;
}

function videosMain(live, data) {
  const all = data.allVideos;
  const links = Object.values(data.services)
    .filter((svc) => live.some((v) => data.services[v.service] === svc))
    .map((svc) => `<a href="${esc(svc.url)}">${esc(svc.name.toLowerCase())}</a>`)
    .join(' y ');
  return `<section class="section section--white" aria-labelledby="videos-all-title">
  <div class="container">
    <div class="section__header" data-animate="fade-up">
      <h2 class="section__title" id="videos-all-title">${esc(all.sectionTitle)}</h2>
      <p class="section__subtitle">${esc(all.sectionIntro)} Más información sobre ${links}.</p>
    </div>
${indent(carousel(live, 'Lista de todos los vídeos', { showText: true }), '    ')}
  </div>
</section>`;
}

function breadcrumbLd(site) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Inicio', item: `${site}/` },
      { '@type': 'ListItem', position: 2, name: 'Vídeos', item: `${site}/videos.html` },
    ],
  };
}

/* ---------- build ---------- */
export function build(root, { preview = false } = {}) {
  const data = JSON.parse(fs.readFileSync(path.join(root, 'data/videos.json'), 'utf8'));
  const site = data.siteUrl;
  const { live, skipped } = loadVideos(data, preview);
  const css = fs.readFileSync(path.join(root, 'css/styles.css'), 'utf8');
  for (const v of live) {
    if (!css.includes(`.${ratioClass(v)}`)) throw new Error(`css/styles.css has no .${ratioClass(v)} (video ${v.slug})`);
    if (!v.thumbnailWidth || !v.thumbnailHeight) throw new Error(`video ${v.slug} has no thumbnailWidth/Height`);
    if (Math.abs(v.thumbnailWidth / v.thumbnailHeight - v.display.width / v.display.height) > 0.003) throw new Error(`thumbnail ratio of ${v.slug} differs from the video ratio`);
  }
  const active = live.length > 0;
  const out = new Map(); // relative path -> new content (null = must not exist)
  const warnings = skipped.map((v) => `skipped (needs youtubeId + uploadDate): ${v.slug}`);

  const links = {
    nav: active ? '<li><a class="nav__link" href="videos.html">Vídeos</a></li>' : '',
    navm: active ? '<li><a class="nav__mobile-link" href="videos.html">Vídeos</a></li>' : '',
    footer: active ? '<li><a class="footer__link" href="videos.html">Vídeos</a></li>' : '',
  };
  const serviceByPage = Object.fromEntries(Object.entries(data.services).map(([k, s]) => [s.url, k]));

  const pageNames = fs.readdirSync(root).filter((f) => f.endsWith('.html'));
  const templatePath = path.join(root, 'scripts/templates/videos.template.html');
  const jobs = pageNames.map((f) => ({ rel: f, text: fs.readFileSync(path.join(root, f), 'utf8') }));

  // videos.html is generated from the template (only when active)
  const hadVideosPage = pageNames.includes('videos.html');
  const videosPageIsGenerated = hadVideosPage && jobs.find((j) => j.rel === 'videos.html').text.includes(GENERATED);
  const idx = jobs.findIndex((j) => j.rel === 'videos.html');
  if (idx >= 0 && videosPageIsGenerated) jobs.splice(idx, 1);
  if (active) {
    let t = fs.readFileSync(templatePath, 'utf8');
    // social-card image: the site's landscape photo (vertical thumbnails get cropped badly in shares)
    t = t.replaceAll('{{OG_IMAGE}}', `${site}/images/copenhaguen-277-07.webp`).replace('<!doctype html>', `<!DOCTYPE html>\n${GENERATED}`);
    jobs.push({ rel: 'videos.html', text: t, generated: true });
  } else if (videosPageIsGenerated) {
    out.set('videos.html', null);
  } else if (hadVideosPage) {
    warnings.push('videos.html exists but is not generated by this script; left untouched');
  }

  for (const job of jobs) {
    let t = job.text;
    t = patch(t, 'nav', links.nav);
    t = patch(t, 'navm', links.navm);
    t = patch(t, 'footer', links.footer);
    const ld = [];
    if (job.rel === 'index.html') {
      const section = active ? homeSection(live, data) : '';
      t = patch(t, 'home', section);
      if (section) live.filter((v) => v.featured).forEach((v) => ld.push(videoLd(v, site)));
    } else if (serviceByPage[job.rel]) {
      const key = serviceByPage[job.rel];
      const section = active ? serviceSection(live, data, key) : '';
      t = patch(t, 'service', section);
      if (section) live.filter((v) => v.service === key).forEach((v) => ld.push(videoLd(v, site)));
    } else if (job.rel === 'videos.html' && job.generated) {
      t = patch(t, 'main', videosMain(live, data));
      ld.push(breadcrumbLd(site));
      live.forEach((v) => ld.push(videoLd(v, site)));
    }
    t = patch(t, 'jsonld', ld.map(ldScript).join('\n'));
    out.set(job.rel, t);
  }

  // sitemap
  const smPath = path.join(root, 'sitemap.xml');
  if (fs.existsSync(smPath)) {
    const last = live.map((v) => v.uploadDate).sort().pop();
    const entry = active
      ? `<url>\n  <loc>${site}/videos.html</loc>\n  <lastmod>${last}</lastmod>\n  <changefreq>monthly</changefreq>\n  <priority>0.7</priority>\n</url>`
      : '';
    out.set('sitemap.xml', patch(fs.readFileSync(smPath, 'utf8'), 'sitemap', entry));
  }
  return { out, warnings, liveCount: live.length };
}

function writeAll(root, out) {
  let changed = 0;
  for (const [rel, content] of out) {
    const p = path.join(root, rel);
    if (content === null) { if (fs.existsSync(p)) { fs.unlinkSync(p); changed++; console.log('removed', rel); } continue; }
    const before = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (before !== content) { fs.writeFileSync(p, content); changed++; console.log('updated', rel); }
  }
  return changed;
}

function diffAll(root, out) {
  const stale = [];
  for (const [rel, content] of out) {
    const p = path.join(root, rel);
    const before = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (before !== content) stale.push(rel);
  }
  return stale;
}

/* ---------- CLI ---------- */
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args[0] === '--preview') {
    const dir = path.resolve(args[1] || '');
    if (!args[1] || dir === REPO || dir.startsWith(REPO + path.sep)) {
      console.error('--preview needs a directory OUTSIDE the repo'); process.exit(2);
    }
    fs.rmSync(dir, { recursive: true, force: true });
    fs.cpSync(REPO, dir, { recursive: true, filter: (s) => !/[\\/](\.git|\.agents|\.claude|node_modules)([\\/]|$)/.test(s) });
    const { out, warnings, liveCount } = build(dir, { preview: true });
    writeAll(dir, out);
    warnings.forEach((w) => console.warn('warn:', w));
    console.log(`preview built in ${dir} with FAKE ids (${liveCount} videos). Never commit this output.`);
  } else {
    const { out, warnings, liveCount } = build(REPO);
    warnings.forEach((w) => console.warn('warn:', w));
    if (args[0] === '--check') {
      const stale = diffAll(REPO, out);
      if (stale.length) { console.error('out of date:', stale.join(', ')); process.exit(1); }
      console.log(`ok (${liveCount} live videos)`);
    } else {
      const n = writeAll(REPO, out);
      console.log(n ? `done (${liveCount} live videos)` : `nothing to change (${liveCount} live videos)`);
    }
  }
}
